    private void LoginbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_LoginbtnActionPerformed
            // System.out.println("Sign up btn clicked");
   String Loginname,Password, query, passWD = null,fname = null, id = null, money = null;
   String SUrl,SUser,SPass;
       SUrl="jdbc:MySQL://localhost:3306/withdaw_user_database";
       SUser="root";
       SPass="";
        int notFound = 0;
  
       try{
       Class.forName("com.mysql.cj.jdbc.Driver");
       Connection con= DriverManager.getConnection(SUrl,SUser,SPass);
       Statement st=con.createStatement();
       
        if("".equals(Lname.getText()))
       {
            JOptionPane.showMessageDialog(new JFrame(), "Log in name is required", "Error",
                        JOptionPane.ERROR_MESSAGE);
       }
       else if("".equals(password.getText()))
       {
            JOptionPane.showMessageDialog(new JFrame(), "Password is required", "Error",
                        JOptionPane.ERROR_MESSAGE);
       }
      
       
       else {
            
            Loginname = Lname.getText();
            Password = password.getText();
              
            query = "SELECT * FROM user WHERE Login_name= '"+Loginname+"'";
            ResultSet rs=st.executeQuery(query);
            while(rs.next()){
              passWD = rs.getString("password");
              fname = rs.getString("full_name");
              id = rs.getString("id");
              money = rs.getString("money");
              notFound=1;
            }
            if(notFound==1&& Password.equals(passWD)){
               Home Homeframe = new Home();
               Homeframe.setUser(fname);
               Homeframe.setID(id);
               Homeframe.setcoin(money);
               Homeframe.setVisible(true);
               Homeframe.pack();
               Homeframe.setLocationRelativeTo(null);
               this.dispose();
            }
            else{
                 JOptionPane.showMessageDialog(new JFrame(), "Incorrect Login name or password", "Error",
                        JOptionPane.ERROR_MESSAGE);
            }
           password.setText("");
            
           
       }
   }
        catch(HeadlessException | ClassNotFoundException | SQLException e){
        System.out.println("Error!"+e.getMessage());
   }
        
    }//GEN-LAST:event_LoginbtnActionPerformed

