    private void depositActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_depositActionPerformed
        // TODO add your handling code here:
          String query, MONEY;
    String SUrl, SUser, SPass;
    SUrl = "jdbc:mysql://localhost:3306/withdaw_user_database";
    SUser = "root";
    SPass = "";

    try {
        Class.forName("com.mysql.cj.jdbc.Driver");
        try (Connection con = DriverManager.getConnection(SUrl, SUser, SPass)) {
            Statement st = con.createStatement();
            String pin = pin1.getText(); // Assuming pin1 is a JTextField where the user enters their PIN
            query = "SELECT full_name, id, money FROM user WHERE pin= '" + pin + "'";
            ResultSet rs = st.executeQuery(query);
            if (rs.next()) {
                String fname = rs.getString("full_name");
                String id = rs.getString("id");
                String money = rs.getString("money");
                
                if ("".equals(withdrawmoney.getText())) {
                    JOptionPane.showMessageDialog(new JFrame(), "Money field is required", "Error", JOptionPane.ERROR_MESSAGE);
                } else {
                    MONEY = withdrawmoney.getText(); 
                    
                    // Check if the user has sufficient balance
                    if (Integer.parseInt(money) >= Integer.parseInt(MONEY)) {
                        // Update the user's balance in the database
                        query = "UPDATE user SET money = money - " + MONEY + " WHERE id = '" + id + "'";
                        st.executeUpdate(query);
                        withdrawmoney.setText("");
                        JOptionPane.showMessageDialog(null, "Your money has been withdrawn! Thank you for using our service!");
                        
                        // Proceed to the login frame
                        Login loginFrame = new Login();
                        loginFrame.setVisible(true);
                        loginFrame.pack();
                        loginFrame.setLocationRelativeTo(null);
                        this.dispose();
                    } else {
                        JOptionPane.showMessageDialog(new JFrame(), "Insufficient balance", "Error", JOptionPane.ERROR_MESSAGE);
                    }
                }
            } else {
                JOptionPane.showMessageDialog(new JFrame(), "Incorrect PIN", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    } catch (ClassNotFoundException | SQLException e) {
        System.out.println("Error: " + e.getMessage());
    }
    }//GEN-LAST:event_depositActionPerformed

