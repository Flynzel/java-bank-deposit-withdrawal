    private void signbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_signbtnActionPerformed
    // System.out.println("Sign up btn clicked");
   String fullname,Loginname,Password, query, PINnumber,pera;
   String SUrl,SUser,SPass;
       SUrl="jdbc:MySQL://localhost: 3306/withdaw_user_database";
       SUser="root";
       SPass="";
   try{
       Class.forName("com.mysql.cj.jdbc.Driver");
       Connection con= DriverManager.getConnection(SUrl,SUser,SPass);
       Statement st=con.createStatement();
       if("".equals(fname.getText()))
       {
           JOptionPane.showMessageDialog(new JFrame(), "Full Name is required", "Error",
        
                   JOptionPane.ERROR_MESSAGE);
       } 
       else if("".equals(Lname.getText()))
       {
            JOptionPane.showMessageDialog(new JFrame(), "Log in name is required", "Error",
                        JOptionPane.ERROR_MESSAGE);
       }
        else if("".equals(coin.getText())){
            JOptionPane.showMessageDialog(new JFrame(), " A little Money is required", "Error",
                        JOptionPane.ERROR_MESSAGE);
        }
      
       else if("".equals(password.getText()))
       {
            JOptionPane.showMessageDialog(new JFrame(), "Password is required", "Error",
                        JOptionPane.ERROR_MESSAGE);
       }
      
       
       else {
            fullname = fname.getText(); 
            Loginname = Lname.getText();
            Password = password.getText();
            PINnumber = pin.getText();
            pera = coin.getText();
           
           
            
            query = "INSERT INTO user(full_name, Login_name, password,Pin,money)"+
                   "VALUES('"+fullname+"', '"+Loginname+"' , '"+Password+"','"+PINnumber+"','"+pera+"')";
            
            st.execute(query);
            fname.setText("");
            Lname.setText("");
            password.setText("");
            coin.setText("");
            showMessageDialog(null, "New account has been created successfully! you can log in now.");
            
             Login login = new Login();
               login.setVisible(true);
               login.pack();
               login.setLocationRelativeTo(null);
               this.dispose();
           
       }
   } catch(Exception e){
        System.out.println("Error!"+e.getMessage());
   }
  
    }//GEN-LAST:event_signbtnActionPerformed

